import { expect, it } from 'vitest';
import * as THREE from 'three';
import { createScope } from '../../../src/shared/lifecycle';
import type { createScene } from '../../../src/chapters/explore/scene';
import { createVehicleRig } from '../../../src/chapters/explore/vehicle-rig';
import {
  createAssemblyReturnState,
  reduceAssemblyReturn,
  stepAssemblyReturn,
} from '../../../src/chapters/explore/assembly-state';

it('keeps authored door, tailgate, light and explosion transforms', () => {
  const scene = new THREE.Scene();
  const roadSurface = new THREE.Group();
  const scope = createScope();
  const rig = createVehicleRig({ scene, roadSurface } as ReturnType<typeof createScene>, scope);
  const root = new THREE.Group();
  const assembly = new THREE.Group();
  assembly.name = 'EV_SUV';
  root.add(assembly);
  const nodes = ['Door_FL', 'Door_FR', 'Tailgate', 'BatteryPack'].map((name, index) => {
    const material = new THREE.MeshStandardMaterial();
    material.name = 'daylight_led';
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(0.1, 0.1, 0.1), material);
    mesh.name = name;
    mesh.position.x = index * 10;
    mesh.rotation.set(0, 0.1, 0.2);
    mesh.userData.explode_vector_blender_m = [0, 1, 0];
    assembly.add(mesh);
    return mesh;
  });
  rig.prepareModel(root);
  rig.prepareExplosionRigs();
  expect(rig.assemblyRoot).toBe(assembly);
  expect(rig.toggleDoors()).toBe(true);
  expect(rig.animating).toBe(true);
  expect(rig.toggleTailgate()).toBe(true);
  expect(rig.toggleLights()).toBe(true);
  rig.update(2);
  expect(rig.animating).toBe(false);
  expect(nodes[0].rotation.y).toBeCloseTo(0.1 - 0.72);
  expect(nodes[1].rotation.y).toBeCloseTo(0.1 + 0.72);
  expect(nodes[2].rotation.z).toBeCloseTo(0.2 - 0.95);
  expect(nodes[0].material.emissiveIntensity).toBe(1.7);
  rig.setExploded(true);
  rig.update(2);
  expect(roadSurface.visible).toBe(false);
  expect(nodes[3].position.y).toBeCloseTo(1.55, 3);
  expect(rig.applyPartFilter('energy')).toBe(1);
  expect(nodes[0].visible).toBe(false);
  expect(nodes[3].visible).toBe(true);
  rig.setExploded(false);
  rig.update(2);
  expect(roadSurface.visible).toBe(true);
  expect(nodes[3].position.y).toBeCloseTo(0, 3);
  expect(rig.toggleLights()).toBe(false);
  expect(nodes[0].material.emissiveIntensity).toBe(0.06);
  scope.dispose();
});

it('freezes rigid leaf details while their door and exploded assembly keep moving', () => {
  const scene = new THREE.Scene(), roadSurface = new THREE.Group(), scope = createScope();
  const rig = createVehicleRig({ scene, roadSurface } as ReturnType<typeof createScene>, scope);
  const root = new THREE.Group(), assembly = new THREE.Group(), door = new THREE.Group();
  assembly.name = 'EV_SUV'; door.name = 'Door_FL';
  door.userData.explode_vector_blender_m = [1, 1, 0];
  const detail = new THREE.Mesh(new THREE.BoxGeometry(.1, .1, .1), new THREE.MeshStandardMaterial());
  detail.position.set(.1, .2, .3);
  door.add(detail); assembly.add(door); root.add(assembly);
  rig.prepareModel(root); rig.prepareExplosionRigs();
  expect(detail.matrixAutoUpdate).toBe(false);
  expect(door.matrixAutoUpdate).toBe(true);
  const before = detail.getWorldPosition(new THREE.Vector3());
  rig.toggleDoors(); rig.update(2); root.updateMatrixWorld(true);
  expect(detail.getWorldPosition(new THREE.Vector3()).distanceTo(before)).toBeGreaterThan(.01);
  rig.setExploded(true); rig.update(2); root.updateMatrixWorld(true);
  const worldPosition = detail.getWorldPosition(new THREE.Vector3());
  const reference = detail.position.clone().applyMatrix4(door.matrixWorld);
  expect(worldPosition.distanceTo(reference)).toBeLessThan(1e-6);
  scope.dispose();
});

it('pauses global explosion writes during teaching and restores cancellation exactly', () => {
  const scene = new THREE.Scene();
  const roadSurface = new THREE.Group();
  const scope = createScope();
  const rig = createVehicleRig({ scene, roadSurface } as ReturnType<typeof createScene>, scope);
  const root = new THREE.Group();
  const assembly = new THREE.Group();
  assembly.name = 'EV_SUV';
  root.add(assembly);
  const wheel = new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1), new THREE.MeshStandardMaterial());
  wheel.name = 'Wheel_FL';
  assembly.add(wheel);
  rig.prepareModel(root);
  rig.prepareExplosionRigs();
  rig.setExploded(true);
  rig.update(0.2);
  const before = wheel.position.clone();
  const state = stepAssemblyReturn(reduceAssemblyReturn(createAssemblyReturnState(), 'next'), 0.5);
  rig.setTeachingAssemblyProgress(state);
  const half = wheel.position.clone();
  rig.update(2);
  expect(wheel.position.toArray()).toEqual(half.toArray());
  rig.clearTeachingAssembly();
  expect(wheel.position.toArray()).toEqual(before.toArray());
  expect(rig.explosionTarget).toBe(1);
  let complete = state;
  complete = stepAssemblyReturn(complete, 0.5);
  for (let i = 0; i < 3; i++) complete = stepAssemblyReturn(reduceAssemblyReturn(complete, 'next'), 1);
  rig.setTeachingAssemblyProgress(complete);
  rig.setExploded(false);
  rig.clearTeachingAssembly();
  rig.update(0.1);
  expect(wheel.position.toArray()).toEqual([0, 0, 0]);
  expect(roadSurface.visible).toBe(true);
  rig.setExploded(true);
  rig.update(2);
  expect(wheel.position.length()).toBeGreaterThan(0);
  scope.dispose();
});
